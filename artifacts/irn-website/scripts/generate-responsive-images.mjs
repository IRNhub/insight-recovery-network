import fs from "node:fs/promises";
import path from "node:path";
import { createHash } from "node:crypto";
import sharp from "sharp";

const root = path.resolve(import.meta.dirname, "..");
const publicRoot = path.join(root, "public");
const outputRoot = path.join(publicRoot, "responsive");
const manifestPath = path.join(root, "src/data/responsive-images.generated.ts");
const profile = "webp-q80-v1";
const candidates = new Map();
async function walk(directory) {
  const entries = await fs.readdir(directory, { withFileTypes: true });
  const nested = await Promise.all(
    entries
      .filter((e) => e.name !== "responsive")
      .map(async (e) => {
        const filename = path.join(directory, e.name);
        return e.isDirectory() ? walk(filename) : [filename];
      }),
  );
  return nested.flat();
}

for (const file of await walk(publicRoot)) {
  const relative = path.relative(publicRoot, file).replaceAll(path.sep, "/");
  if (
    !/\.(png|jpe?g|webp)$/i.test(file) ||
    /(^|\/)(og-|favicon|apple-touch|icon-|logo)/i.test(relative)
  )
    continue;
  candidates.set(file, { url: `/${relative}` });
}
for (const source of (await walk(path.join(root, "src"))).filter(
  (f) => /\.(tsx?|jsx?)$/.test(f) && f !== manifestPath,
)) {
  const text = await fs.readFile(source, "utf8");
  for (const match of text.matchAll(
    /from\s+["']((?:@\/assets\/|@assets\/)[^"']+\.(?:png|jpe?g|webp))["']/g,
  )) {
    const specifier = match[1];
    const file = specifier.startsWith("@/")
      ? path.join(root, "src", specifier.slice(2))
      : path.resolve(
          root,
          "../../attached_assets",
          specifier.slice("@assets/".length),
        );
    candidates.set(file, { specifier });
  }
}
await fs.mkdir(outputRoot, { recursive: true });
const imports = [];
const entries = [];
const publicManifest = {};
let originals = 0;
let optimised = 0;
for (const [file, reference] of [...candidates].sort(([a], [b]) =>
  a.localeCompare(b),
)) {
  const buffer = await fs.readFile(file);
  if (buffer.length < 60_000) continue;
  const meta = await sharp(buffer).metadata();
  if (!meta.width || !meta.height || meta.width < 480 || (meta.pages ?? 1) > 1)
    continue;
  const rotated = (meta.orientation ?? 1) >= 5;
  const width = rotated ? meta.height : meta.width;
  const height = rotated ? meta.width : meta.height;
  const hash = createHash("sha256")
    .update(buffer)
    .update(profile)
    .digest("hex")
    .slice(0, 12);
  const name = path
    .basename(file, path.extname(file))
    .replace(/[^a-zA-Z0-9_-]/g, "-");
  const widths = [
    ...new Set(
      [480, 800, 1200, Math.min(width, 1600)].filter((w) => w <= width),
    ),
  ].sort((a, b) => a - b);
  const variants = [];
  for (const size of widths) {
    const url = `/responsive/${name}-${hash}-${size}.webp`;
    const output = path.join(publicRoot, url);
    try {
      await fs.access(output);
    } catch {
      await sharp(buffer)
        .rotate()
        .resize({ width: size, withoutEnlargement: true })
        .webp({ quality: 80, effort: 4 })
        .toFile(output);
    }
    variants.push({ url, width: size, bytes: (await fs.stat(output)).size });
  }
  const fallback = variants.find((v) => v.width >= 1200) ?? variants.at(-1);
  if (!fallback || fallback.bytes >= buffer.length) continue;
  let key = JSON.stringify(reference.url);
  if (reference.specifier) {
    const variable = `image${imports.length}`;
    imports.push(
      `import ${variable} from ${JSON.stringify(reference.specifier)};`,
    );
    key = `[${variable}]`;
  }
  entries.push(
    `${key}: ${JSON.stringify({ src: fallback.url, srcSet: variants.map((v) => `${v.url} ${v.width}w`).join(", "), width, height })}`,
  );
  publicManifest[reference.url ?? reference.specifier] = {
    src: fallback.url,
    srcSet: variants.map((v) => `${v.url} ${v.width}w`).join(", "),
    width,
    height,
  };
  originals += buffer.length;
  optimised += fallback.bytes;
}
const content = `// Generated by scripts/generate-responsive-images.mjs. Original artwork is preserved.\n${imports.join("\n")}\nexport const responsiveImages: Record<string, { src: string; srcSet: string; width: number; height: number }> = {\n${entries.join(",\n")}\n};\n`;
let old = "";
try {
  old = await fs.readFile(manifestPath, "utf8");
} catch {}
if (old !== content) await fs.writeFile(manifestPath, content);
await fs.writeFile(
  path.join(outputRoot, "manifest.json"),
  JSON.stringify(publicManifest, null, 2),
);
console.log(
  JSON.stringify({
    images: entries.length,
    originalBytes: originals,
    fallbackBytes: optimised,
    savedPercent: Math.round((1 - optimised / originals) * 100),
  }),
);
